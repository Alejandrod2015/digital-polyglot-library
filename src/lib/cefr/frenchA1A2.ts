//        la más frecuente de las 16 (dialectique) ocupa el puesto 13.650,
//        más del doble del corte. Ninguna entra.
//   Motivadoras del encargo original (souvenir, blague, habitude, discours,
//   accent) caen en los puestos 321-2036: entran con margen.
// LÍMITE reconocido: frecuencia pura no es lo mismo que nivel MCER (por eso
