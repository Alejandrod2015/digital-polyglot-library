//   1. Para cada lema: frecuencia = promedio de freqlemfilms2 y freqlemlivres
//      (subtítulos + libros, por millón de palabras).
//   2. Se ordena todo Lexique por esa frecuencia, excluyendo nombres propios,
//      onomatopeyas, símbolos, abreviaturas y números (cgram NAM/ONO/SYM/
//      ABR/NUM), palabras con dígitos o guion bajo, y una lista corta de
//      soeces/insultos que la frecuencia de subtítulos sube alto sin que eso
//      diga nada de su nivel (register, no nivel; ya tienen su propia
